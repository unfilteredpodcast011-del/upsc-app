  static String get(String key, String langCode, {Map<String, String>? params}) {
    final lang = _localizedValues.containsKey(langCode) ? langCode : 'en';
    String str = _localizedValues[lang]?[key] ?? _localizedValues['en']?[key] ?? key;
    if (params != null) {
      params.forEach((k, v) {
        str = str.replaceAll('{$k}', v);
      });
    }
    return str;
  }

  // Developer check: Ensures all English keys exist in Tamil and Hindi
  static List<String> validateLocalizationKeys() {
    final enKeys = _localizedValues['en']!.keys;
    final List<String> missing = [];
    for (final k in enKeys) {
      if (!_localizedValues['ta']!.containsKey(k)) missing.add('ta missing: $k');
      if (!_localizedValues['hi']!.containsKey(k)) missing.add('hi missing: $k');
    }
    return missing;
  }
